import assert from 'node:assert/strict';
import { test } from 'node:test';
import { normalizeOrderId } from './orderId';

test('accepts order IDs generated by the current checkout', () => {
  assert.equal(normalizeOrderId('SYF0123456789ABCDEF012345'), 'SYF0123456789ABCDEF012345');
});

test('accepts safe historical order ID formats and trims surrounding whitespace', () => {
  assert.equal(normalizeOrderId('  SYF-LEGACY-1234  '), 'SYF-LEGACY-1234');
  assert.equal(normalizeOrderId('order_legacy_123'), 'order_legacy_123');
});

test('rejects missing, non-string, overlong, or unsafe values', () => {
  assert.equal(normalizeOrderId(undefined), null);
  assert.equal(normalizeOrderId(null), null);
  assert.equal(normalizeOrderId(12345), null);
  assert.equal(normalizeOrderId(''), null);
  assert.equal(normalizeOrderId('abc'), null);
  assert.equal(normalizeOrderId('SYF bad id'), null);
  assert.equal(normalizeOrderId('x'.repeat(129)), null);
});
